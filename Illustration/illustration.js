const illustrationsByYear = {
    2024: illustrations2024,
    2025: illustrations2025,
    2026: illustrations2026
};

const years = [2024, 2025, 2026];
const year = document.body.dataset.year;
const currentYear = Number(year);

const currentIndex =
    years.indexOf(currentYear);

const previousYear =
    years[
    (currentIndex - 1 + years.length) % years.length
    ];

const nextYear =
    years[
    (currentIndex + 1) % years.length
    ];

const yearNav =
    document.querySelector("#yearNav");

yearNav.innerHTML = `
    <a href="${previousYear}.html" class="detail-nav-btn">
        ← ${previousYear}
    </a>

    <a href="${nextYear}.html" class="detail-nav-btn">
        ${nextYear} →
    </a>
`;


const illustrations = illustrationsByYear[year];

const illustrationGrid =
    document.querySelector("#illustrationGrid");

/* Create Items */

illustrations.forEach(work => {

    const item = document.createElement("article");

    item.className = "illustration-item";

    item.innerHTML = `
        <img src="${work.image}" alt="${work.title}">

        <div class="illustration-tooltip">
            <strong>${work.title}</strong>
            <span>${work.description}</span>
        </div>
    `;

    illustrationGrid.appendChild(item);


    /* Tooltip */

    const tooltip =
        item.querySelector(".illustration-tooltip");


    item.addEventListener("mouseenter", () => {
        tooltip.style.opacity = "1";
        tooltip.style.visibility = "visible";
    });


    item.addEventListener("mousemove", event => {

        tooltip.style.left =
            `${event.clientX + 12}px`;

        tooltip.style.top =
            `${event.clientY + 12}px`;
    });


    item.addEventListener("mouseleave", () => {
        tooltip.style.opacity = "0";
        tooltip.style.visibility = "hidden";
    });
});


/* Masonry Layout */

function layoutMasonry() {

    const items =
        document.querySelectorAll(".illustration-item");

    const columns =
        window.innerWidth <= 768 ? 2 : 4;

    const gap =
        window.innerWidth <= 768 ? 10 : 16;

    const gridWidth =
        illustrationGrid.clientWidth;

    const columnWidth =
        (gridWidth - gap * (columns - 1)) / columns;


    /* 각 column의 현재 높이 */

    const columnHeights =
        new Array(columns).fill(0);


    items.forEach((item, index) => {

        /* 이미지 너비 설정 */
        item.style.width =
            `${columnWidth}px`;


        /* 현재 가장 짧은 column 찾기 */
        let columnIndex =
            columnHeights.indexOf(
                Math.min(...columnHeights)
            );


        /* 위치 */
        const x =
            columnIndex *
            (columnWidth + gap);

        const y =
            columnHeights[columnIndex];


        item.style.left =
            `${x}px`;

        item.style.top =
            `${y}px`;


        /* 이미지 높이 */
        const image =
            item.querySelector("img");

        const itemHeight =
            image.offsetHeight;


        /* column 높이 업데이트 */
        columnHeights[columnIndex] =
            y + itemHeight + gap;
    });


    /* Grid 전체 높이 */
    const maxHeight =
        Math.max(...columnHeights);

    illustrationGrid.style.height =
        `${maxHeight - gap}px`;
}

/* Images Loaded */
window.addEventListener("load", () => {
    layoutMasonry();
});

/* Resize */
window.addEventListener("resize", () => {
    layoutMasonry();
});